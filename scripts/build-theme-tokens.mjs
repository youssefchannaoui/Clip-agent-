#!/usr/bin/env node
/**
 * Tokenise the colours that live in INLINE styles.
 *
 * A stylesheet cannot override an inline style, and 13% of the elements on the
 * Home screen carry their own colour — every chip, bar and pill the adapter
 * draws. Those are rewritten to `var(--dc-n-XXXXXX, #XXXXXX)`, which works
 * perfectly well in a style attribute, and this emits the variable block that
 * gives each one a dark value (its own) and a daylight one.
 *
 * The literal stays as the fallback, so a browser that somehow never loads the
 * token sheet renders exactly what it renders today.
 *
 * Only NEUTRALS are touched. Red still means failed and green still means
 * posted; re-tinting those would be a second design rather than the same one
 * in daylight.
 *
 *   node scripts/build-theme-tokens.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { daylight } from './theme-palette.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['src/public/studio-adapter.js', 'src/public/index.html'];
const TARGET = path.join(ROOT, 'src/public/studio-theme.generated.css');

const found = new Map();
let rewritten = 0;

for (const rel of FILES) {
  const file = path.join(ROOT, rel);
  const text = fs.readFileSync(file, 'utf8');
  /*
   * Tokens ALREADY in the file count too.
   *
   * This script rewrites literals into var() references, so on a second run
   * there are fewer literals to find — and emitting only what it found this
   * time would drop every variable defined by the previous run while the
   * files still referenced them. Every reference is collected first, so the
   * output is complete whether this is the first run or the tenth.
   */
  for (const ref of text.matchAll(/var\((--dc-n-([0-9a-f]{6})),\s*(#[0-9A-Fa-f]{6})\)/g)) {
    const light = daylight(ref[3]);
    if (light) found.set(ref[1], { dark: ref[3].toUpperCase(), light });
  }
  const out = [];
  let last = 0;
  for (const match of text.matchAll(/#[0-9A-Fa-f]{6}\b/g)) {
    const hex = match[0];
    // Already tokenised: the literal sitting inside a var() fallback is the
    // fallback, not a colour to tokenise a second time.
    const before = text.slice(Math.max(0, match.index - 24), match.index);
    if (before.includes('var(--dc-') && before.lastIndexOf('var(--dc-') > before.lastIndexOf(')')) continue;
    /*
     * A meta tag is not styled, so `var(...)` there is read as a colour NAME
     * and the browser paints nothing — the address bar went transparent until
     * this was caught. Anything that is not a style value stays a literal.
     */
    const line = text.slice(text.lastIndexOf('\n', match.index) + 1,
      (text.indexOf('\n', match.index) + 1 || text.length));
    if (/<meta\b/i.test(line) || /setAttribute\(\s*['"]content['"]/.test(line)) continue;
    /*
     * An SVG PRESENTATION ATTRIBUTE is not a style value either. `stroke=
     * "var(--x, #D9B478)"` does not resolve, and the path then draws with the
     * default — a black fill and no stroke. It reached the arch mark in the
     * onboarding strip before it was caught. The gold does not need theming
     * anyway: it is the brand colour in both themes.
     */
    if (/(?:stroke|fill|stop-color|flood-color|lighting-color)\s*=\s*["'][^"']*$/.test(before)) continue;
    // Anything the palette has an answer for, not only the greys: the status
    // colours are named there too, and an inline #7FD1A6 stat number stayed a
    // pastel on paper while the same green in the stylesheet had darkened.
    const light = daylight(hex);
    if (!light) continue;
    const name = `--dc-n-${hex.slice(1).toLowerCase()}`;
    found.set(name, { dark: hex.toUpperCase(), light });
    out.push(text.slice(last, match.index), `var(${name}, ${hex})`);
    last = match.index + hex.length;
    rewritten += 1;
  }
  out.push(text.slice(last));
  fs.writeFileSync(file, out.join(''));
}

const names = [...found.keys()].sort();
const banner = `/* GENERATED by scripts/build-theme-tokens.mjs.
   Do not edit: re-run the script. Every value below is a colour that appears
   in an INLINE style, which no stylesheet can override — so the inline style
   reads the variable instead. The dark value is the colour that was there. */\n`;
const body = `:root{\n${names.map(n => `  ${n}: ${found.get(n).dark};`).join('\n')}\n}\n`
  + `:root.dc-light,\nbody.dc-light{\n${names.map(n => `  ${n}: ${found.get(n).light};`).join('\n')}\n}\n`;
fs.writeFileSync(TARGET, banner + body);
console.log(`Tokenised ${rewritten} inline colour(s) into ${names.length} variables `
  + `→ ${path.relative(ROOT, TARGET)}`);
